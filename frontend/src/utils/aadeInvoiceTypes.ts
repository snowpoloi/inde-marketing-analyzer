export function aadeInvoiceTypeLabel(code: string | null | undefined) {
  const key = String(code ?? "").trim();
  return key ? aadeInvoiceTypeLabels[key] : "";
}

export function formatAadeInvoiceType(code: string | null | undefined) {
  const key = String(code ?? "").trim();
  if (!key) {
    return "-";
  }
  const label = aadeInvoiceTypeLabels[key];
  return label ? `${key} - ${label}` : key;
}
