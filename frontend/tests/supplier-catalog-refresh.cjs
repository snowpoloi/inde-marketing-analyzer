const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");
const source = fs.readFileSync(path.join(__dirname, "../src/utils/supplierCatalogRefresh.ts"), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const target = { exports: {} };
new Function("exports", "module", compiled)(target.exports, target);
const { catalogDataChanged } = target.exports;
const before = { feeds: [{id:"a",last_synced_at:"first",status:"success"}, {id:"b",last_synced_at:"first",status:"success"}],
  cost_revisions: {a:"first",b:"first"}, sync_revision:"first" };
const next = () => structuredClone(before);
assert.equal(catalogDataChanged(before, next(), "a"), false);
let state = next(); state.feeds[0].status = "running";
assert.equal(catalogDataChanged(before, state, "a"), false);
state.feeds[1].last_synced_at = "second";
assert.equal(catalogDataChanged(before, state, "a"), false);
assert.equal(catalogDataChanged(before, state, ""), true);
state = next(); state.cost_revisions.b = "second";
assert.equal(catalogDataChanged(before, state, "a"), false);
assert.equal(catalogDataChanged(before, state, ""), true);
state.cost_revisions.a = "second";
assert.equal(catalogDataChanged(before, state, "a"), true);
state = next(); state.feeds[0].last_synced_at = "second";
assert.equal(catalogDataChanged(before, state, "a"), true);
state = next(); state.sync_revision = "second";
assert.equal(catalogDataChanged(before, state, "a"), true);
state = next(); state.feeds = state.feeds.slice(1);
assert.equal(catalogDataChanged(before, state, "a"), true);
assert.equal(catalogDataChanged(before, state, "b"), false);
console.log("11 supplier catalog refresh cases passed.");
